"""GitHub-ready zip of TRIAD_det: TRIAD_det/TRIAD-Det_NoCheckpoints.zip (replaces the older all-in-one zip). Safe to re-run.

Everything in TRIAD_det that GitHub accepts goes in, under a top folder TRIAD_det/. Left out:
  - the datasets (they live next to TRIAD_det, are third-party and several GB; see the dataset sources in README.md)
  - model weights (.pt .pth .ckpt .onnx .safetensors .bin), including yolo11s.pt / yolov8s.pt (Ultralytics downloads them)
  - everything under checkpoints folders except CSV logs
  - results/_adaptation_work (copies of dataset images made by the stopped adaptation run), _work, smoke runs
  - .venv, caches, zips, runs/<run>/<dataset>/batches (mislabelled; correct ones are in OUTPUT/batches)
  - any file over GitHub's 100 MB per-file limit (listed in EXCLUDED.md inside the zip)
The zip also gets a .gitignore that matches these rules.

    .venv/Scripts/python.exe tools/make_github_zip.py
"""
import os
import re
import zipfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]           # TRIAD_det
TARGET = REPO / "TRIAD-Det_NoCheckpoints.zip"
TEMP = TARGET.with_suffix(".zip.part")
SKIP_DIRS = {".venv", "__pycache__", ".git", "_work", "_adaptation_work", "smoke", ".pytest_cache", ".ipynb_checkpoints"}
WEIGHTS = {".pt", ".pth", ".ckpt", ".onnx", ".safetensors", ".bin"}
STORED = {".png", ".jpg", ".jpeg", ".bmp", ".pdf", ".gz"}
GITHUB_LIMIT = 100 * 10**6
TEXT = {".py", ".md", ".txt", ".yaml", ".yml", ".json", ".csv", ".tex", ".log", ".out", ".err", ".bib"}
SECRET = re.compile(r"(ghp_[A-Za-z0-9]{20,}|hf_[A-Za-z0-9]{30,}|sk-[A-Za-z0-9]{20,}|AKIA[0-9A-Z]{16}|@gmail\.com)")

GITIGNORE = """# generated by tools/make_github_zip.py
.venv/
__pycache__/
.pytest_cache/
.ipynb_checkpoints/
_work/
_adaptation_work/
smoke/
*.pt
*.pth
*.ckpt
*.onnx
*.safetensors
*.bin
*.zip
*.zip.part
**/checkpoints/**
!**/checkpoints/**/
!**/checkpoints/**/*.csv
runs/*/*/batches/
"""


def skip_reason(path, parts):
    suffix = path.suffix.lower()
    if suffix in WEIGHTS:
        return "weights"
    if suffix in (".zip", ".part"):
        return "zip"
    if "checkpoints" in parts and suffix != ".csv":
        return "checkpoint"
    if len(parts) > 2 and parts[0] == "runs" and "batches" in parts:
        return "mislabelled batches"
    if path.stat().st_size > GITHUB_LIMIT:
        return "over 100 MB"
    return None


def main():
    kept, too_big, secrets, total = [], [], [], 0
    for folder, dirs, files in os.walk(REPO):
        dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS)
        for name in sorted(files):
            path = Path(folder) / name
            rel = path.relative_to(REPO)
            why = skip_reason(path, rel.parts)
            if why == "over 100 MB":
                too_big.append((rel.as_posix(), path.stat().st_size))
            if why:
                continue
            if path.suffix.lower() in TEXT and path.stat().st_size < 30 * 10**6:
                if SECRET.search(path.read_text(encoding="utf-8", errors="ignore")):
                    secrets.append(rel.as_posix())
            kept.append((path, rel))
            total += path.stat().st_size
    excluded = ["# Not in this zip", "",
                "- Datasets (SteelDefectX-DET, NEU-DET, GC10-DET, X-SDD-DET): place them in the folder that contains `TRIAD_det/`"
                " (`data_root: ..` in `configs/`, `../..` in `TRIAD_Det_Risk_Control/config/`).",
                "- Model weights and checkpoints (only CSV training logs are kept). Ultralytics downloads `yolo11s.pt` and `yolov8s.pt`.",
                "- `TRIAD_Det_Risk_Control/results/_adaptation_work/` (dataset image copies from the stopped adaptation run).",
                "", "Files over GitHub's 100 MB limit (regenerated by the pipeline, or add them with Git LFS):", ""]
    excluded += [f"- `{r}` ({s / 1e6:.0f} MB)" for r, s in too_big] or ["- none"]
    with zipfile.ZipFile(TEMP, "w", allowZip64=True) as z:
        for path, rel in kept:
            kind = zipfile.ZIP_STORED if path.suffix.lower() in STORED else zipfile.ZIP_DEFLATED
            z.write(path, Path("TRIAD_det") / rel, kind)
        z.writestr("TRIAD_det/.gitignore", GITIGNORE)
        z.writestr("TRIAD_det/EXCLUDED.md", "\n".join(excluded) + "\n")
    with zipfile.ZipFile(TEMP) as z:
        bad = z.testzip()
        info = z.infolist()
    assert bad is None, bad
    assert max(i.file_size for i in info) <= GITHUB_LIMIT
    os.replace(TEMP, TARGET)
    names = [i.filename for i in info]
    print(TARGET, f"{TARGET.stat().st_size / 2**30:.2f} GB (from {total / 2**30:.2f} GB)", len(names), "files; corrupt: None")
    print("largest file in zip:", f"{max(i.file_size for i in info) / 1e6:.1f} MB")
    print("over 100 MB, left out:", too_big)
    print("possible secrets / e-mail in:", secrets)
    print("weights inside:", sum(Path(n).suffix.lower() in WEIGHTS for n in names))
    for key in ("paper.md", "7 NOV NOVELTY.md", "7 NOV new updated.md", "7 nov.md", "failure_cases/fig_failure_cases.tex",
                "tools/make_failure_figures.py", "class_samples/fig_steeldefectx_classes.tex", "manuscript/sn-article_draft_rev2.tex",
                "7 NOV csv/target_adaptation.csv", "TRIAD_Det_Risk_Control/results/tables/full/in_domain_selective.csv"):
        print(" ", key, f"TRIAD_det/{key}" in names)
    print("top folders:", sorted({n.split("/")[1] for n in names}))


if __name__ == "__main__":
    main()
